<?php

namespace App\Http\Middleware;

use Illuminate\Foundation\Http\Middleware\TransformsRequest;

/**
 * نزع محارف الاتجاه من كل ما يصل من المتصفّح.
 *
 * ── لماذا ───────────────────────────────────────────────────
 * الواجهة تُدخل محرفَي عزل (FSI وPDI) في النصّ المختلط لتصحّح
 * ترتيبه على الشاشة. وهما بلا شكل، فلا يراهما أحد — ولكن ما يُعرض
 * في حقلٍ قد يُحفظ منه: نصّ الكتابة الذي يُعاد تحريره، وملاحظة
 * الاستراحة، وأي مسوّدة تعود من الصفحة إلى الخادم.
 *
 * ولو حُفظت لتراكمت: عزلٌ فوق عزل في كل حفظ، وتشويهٌ لأي مقارنة
 * نصّية بعد ذلك. فالقاعدة: **العزل زينة عرض لا جزء من النصّ**،
 * ومكانه الشاشة وحدها.
 *
 * ── ولماذا هنا لا في كل متحكّم ─────────────────────────────
 * لأن الاحتراس الذي يُكتب في مكان واحد يصمد، والذي يُكتب في كل
 * متحكّم يُنسى في المتحكّم القادم.
 */
class StripBidiMarks extends TransformsRequest
{
    /**
     * محارف التحكّم في الاتجاه:
     * ‎200E/200F‎ العلامتان · ‎061C‎ العربية · ‎2066–2069‎ العزل ·
     * ‎202A–202E‎ التضمين والتجاوز.
     */
    protected const MARKS = '/[\x{200E}\x{200F}\x{061C}\x{2066}-\x{2069}\x{202A}-\x{202E}]/u';

    protected function transform($key, $value)
    {
        if (! is_string($value)) {
            return $value;
        }

        return preg_replace(self::MARKS, '', $value) ?? $value;
    }
}
