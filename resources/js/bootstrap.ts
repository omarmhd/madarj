import axios from 'axios';
import { isolateDeep } from '@/lib/bidi';

window.axios = axios;
window.axios.defaults.headers.common['X-Requested-With'] = 'XMLHttpRequest';

/**
 * عزل النصّ المختلط في كل ما يعود من الخادم.
 *
 * ── الثقب الذي يسدّه ────────────────────────────────────────
 * كان العزل يقع على خصائص Inertia وحدها، و**أكثر النصّ المختلط لا
 * يمرّ بها**: شرح التمارين يعود عبر `axios` بعد كل إجابة، وثلاثمئة
 * وأحد عشر شرحاً من أربعمئة فيه عربيّ وإنجليزيّ معاً:
 *
 *   «sheep فيها كسرة ممدودة ‎/iː/‎. أما ship فقصيرة ‎/ɪ/‎.»
 *
 * فكان يُعرض بترتيب مقلوب في أهمّ لحظة تعليمية في التمرين — لحظة
 * أن يعرف المتدرّب لماذا أخطأ.
 *
 * ── ولماذا هنا ─────────────────────────────────────────────
 * سبعة مواضع في المنصة تنادي `axios` اليوم، وسيزيد. والمعترِض
 * موضعٌ واحد يمرّ به كل نداء — الموجود والقادم — فلا يُنسى واحد.
 *
 * ── والطلب لا يُمسّ ────────────────────────────────────────
 * العزل على الاستجابة وحدها. وما يُرسَل إلى الخادم يبقى نظيفاً،
 * ويُنزَع منه ما بقي في `StripBidiMarks` — فالعزل زينة عرض لا
 * جزءٌ من النصّ.
 */
axios.interceptors.response.use((response) => {
  response.data = isolateDeep(response.data);

  return response;
});
