/**
 * عزل قيمةٍ في شجرة JSX.
 *
 * ── لماذا عنصر لا صنف ──────────────────────────────────────
 * حين يجاور نصٌّ عربيٌّ مكتوبٌ في JSX تعبيراً إنجليزيّاً، فهما عقدتا
 * نصّ في تدفّقٍ واحد — وخوارزمية الاتجاه ترتّبهما معاً فينقلب
 * الترقيم بينهما:
 *
 *   <p>الإجابة: {answer}</p>
 *
 * و`<bdi>` عنصرٌ في HTML غرضه هذا بالضبط: عزل اتجاهيّ لما بداخله.
 * لا صنف ولا نمط ولا محرف — العنصر نفسه هو الحلّ.
 *
 * والاستعمال: لُفَّ بها **كل قيمة** تُعرض بين نصٍّ عربيّ ولا تعرف
 * لغتها يقيناً. والأرقام مستثناة — الرقم ضعيف الاتجاه.
 */
export default function Bdi({ children }: { children: React.ReactNode }) {
  return <bdi>{children}</bdi>;
}
