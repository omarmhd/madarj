/**
 * عزل النصّ اللاتيني داخل الفقرة العربية.
 *
 * ── المشكلة ─────────────────────────────────────────────────
 * الحرف اللاتيني داخل جملة عربية لا يقف حيث كُتب. المتصفّح يطبّق
 * خوارزمية Unicode ثنائية الاتجاه، وفيها **الترقيم محايد**: النقطة
 * والقوس والفاصلة تأخذ اتجاه ما حولها لا اتجاهاً ثابتاً. فإذا وقع
 * ترقيمٌ بين نصّين لاتينيين ضُمّ إليهما وانقلب معهما.
 *
 * ولهذا كانت هذه الجملة تُقرأ خطأً:
 *
 *   المكتوب : نسيان الـ s. «He work» خطأ
 *   المعروض : نسيان الـ .s «He work» خطأ    ← النقطة هاجرت
 *
 * لأن s وHe work لاتينيان، وما بينهما نقطةٌ وقوسٌ محايدان، فصار
 * الثلاثة مقطعاً لاتينياً واحداً رُتّب من اليسار.
 *
 * ── الحلّ ───────────────────────────────────────────────────
 * محرفا العزل FSI وPDI. يغلّفان المقطع اللاتيني فيصير في نظر
 * الخوارزمية **رمزاً واحداً**: يُرتَّب داخله من اليسار، ويُوضَع في
 * الجملة العربية حيث كُتب تماماً. والترقيم خارجه يبقى عربياً فلا
 * يهاجر. وهما محرفان بلا شكل — لا يزيدان عرضاً ولا يُريان.
 *
 * ── لماذا هنا لا في المحتوى ─────────────────────────────────
 * المصاب 1245 حقلاً عربياً في اثنين وثلاثين اسم حقل مختلف، وأي
 * إصلاح في الـJSON يعني عملاً يدوياً يتكرّر مع كل محتوى جديد.
 * فالعزل يقع **عند العرض**: مرّة واحدة على كل ما يصل من الخادم،
 * فيشمل الموجود والقادم بلا استثناء.
 */

const FSI = '⁨';
const PDI = '⁩';

/** محارف الاتجاه كلّها — تُنزع من أي نصّ قبل مقارنته أو حفظه */
const MARKS_CLASS = '[\\u200E\\u200F\\u061C\\u2066-\\u2069\\u202A-\\u202E]';
const MARKS_ALL = new RegExp(MARKS_CLASS, 'g');
// نسخة بلا راية عامّة للفحص: الراية العامّة تحفظ موضعها بين
// النداءات فيكذب الفحص التالي على النصّ نفسه
const MARKS_ANY = new RegExp(MARKS_CLASS);

/** حروف قوية الاتجاه من اليسار: لاتينية وIPA وملحقاتها */
const L =
  'A-Za-z' +
  // لاتينية موسّعة: æ و ø و é… وحرفا الضرب والقسمة مستثنيان
  '\u00C0-\u00D6\u00D8-\u00F6\u00F8-\u00FF' +
  '\u0100-\u017F\u0180-\u024F' +
  // اليونانية: ‎θ‎ و‎ð‎ وأمثالها في رموز النطق، واتجاهها من اليسار
  '\u0370-\u03FF' +
  // الأبجدية الصوتية الدولية وملحقاتها — يكثر ورودها في النطق
  '\u0250-\u02AF\u02B0-\u02FF\u1D00-\u1D7F\u1E00-\u1EFF';

/** ما يجوز أن يقع داخل المقطع: ترقيم ملتصق ومسافات */
/*
 * `String.raw` لا زينة: الصنف فيه `\[` و`\]`، وفي السلسلة
 * العادية يبتلع TypeScript الشرطة المائلة فيصير الصنف `[` و`]`
 * — فينغلق عند أول `]` ويسقط نصف التعبير صامتاً.
 */
const MID = String.raw` 	0-9'’–—./:,;()\[\]&-`;

/**
 * المقطع اللاتيني: يبدأ بحرف وينتهي بحرف أو رقم.
 *
 * وانتهاؤه بحرف مقصود — النقطة الأخيرة تخصّ الجملة العربية لا
 * المقطع، فتبقى خارجه لتُرسَم في يسار السطر حيث ينبغي.
 */
// حرفٌ واحد يجوز أن يسبق المقطع أو يليه: شرطة اللاصقة (‎-s‎ و‎-ing‎)
// وشرطتا النطق الصوتي. وبدونهما تُترك الشرطة للعربية فتُرسم في
// الجهة الخطأ من الحرف الذي تخصّه.
const EDGE = '[-/]?';
const RUN = new RegExp(
  `${EDGE}[${L}][${L}${MID}]*[${L}0-9]${EDGE}|${EDGE}[${L}]${EDGE}`,
  'g',
);

const ARABIC = /[؀-ۿݐ-ݿﭐ-﷿ﹰ-﻿]/;
const LATIN = new RegExp(`[${L}]`);

/** نزع محارف الاتجاه — للمقارنة والحفظ والنطق */
export function strip(text: string): string {
  return MARKS_ANY.test(text) ? text.replace(MARKS_ALL, '') : text;
}

/**
 * عزل كل مقطع لاتيني في نصّ عربي.
 *
 * لا يمسّ النصّ الخالص — عربياً كان أو إنجليزياً — لأن الاختلاط
 * وحده هو ما يُربك الخوارزمية.
 */
export function isolate(text: string): string {
  if (!text || text.includes(FSI)) return text;
  if (!ARABIC.test(text) || !LATIN.test(text)) return text;

  return text.replace(RUN, (run) => (LATIN.test(run) ? FSI + run + PDI : run));
}

/**
 * عزل قيمةٍ تُركَّب داخل نصّ عربي في الشفرة.
 *
 * ── الثقب الذي تسدّه ───────────────────────────────────────
 * `isolate` تتخطّى النصّ الخالص عمداً — والسلسلة الإنجليزية وحدها
 * لا تحتاج عزلاً. لكن حين تُركَّب في قالبٍ عربيّ **في الشفرة** فالناتج
 * مختلط ولم يمرّ بالعزل قطّ:
 *
 *   `استمع إلى ${text}`        ← والـ text إنجليزيّ
 *   `${groupName(g)} — كلمة`   ← والاسم قد يكون إنجليزيّاً
 *
 * ── القاعدة ────────────────────────────────────────────────
 * **كل قيمة نصّية تُركَّب في نصّ عربي تُغلَّف بـ`iso`** — بلا سؤال
 * عن لغتها. فـFSI يستنتج الاتجاه من أول حرف قويّ فيها، فتغليف
 * العربية به لا يضرّ، وتغليف الإنجليزية به هو المطلوب.
 *
 * والأرقام لا تحتاجها: الرقم ضعيف الاتجاه ويُرسَم في موضعه.
 */
export function iso(text: string | null | undefined): string {
  if (!text) return '';

  return text.includes(FSI) ? text : FSI + text + PDI;
}

/**
 * عزل كل نصّ في شجرة الخصائص القادمة من الخادم.
 *
 * يُعيد المرجع نفسه حين لا يتغيّر شيء، فلا تُنسَخ الشجرة كاملة ولا
 * تُعاد الرسوم بلا سبب — وأكثر ما يصل من الخادم لا يحتاج تغييراً.
 */
export function isolateDeep<T>(value: T): T {
  if (typeof value === 'string') return isolate(value) as unknown as T;

  if (Array.isArray(value)) {
    let changed = false;
    const out = value.map((v) => {
      const n = isolateDeep(v);
      if (n !== v) changed = true;
      return n;
    });
    return (changed ? out : value) as unknown as T;
  }

  // الكائنات العادية فقط — لا تواريخ ولا دوالّ ولا عناصر React
  if (value && typeof value === 'object' && (value as any).constructor === Object) {
    let changed = false;
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      const n = isolateDeep(v);
      if (n !== v) changed = true;
      out[k] = n;
    }
    return (changed ? out : value) as unknown as T;
  }

  return value;
}
