/**
 * تنظيف نصوص المحتوى قبل عرضها للمتعلّم.
 *
 * ملفات المحتوى تحمل مراجع أقسام الكتاب (§2 · §8.2 · §4.1) لأن المنصة
 * تحويل كتاب، والمراجع تفيد من يؤلّف المحتوى ويراجعه.
 *
 * لكنها لا تفيد المتعلّم إطلاقاً: «§2 رموز النطق + §3 عبارات النجاة»
 * تُقرأ كترقيم غامض، بينما «رموز النطق + عبارات النجاة» تقول ما في
 * المهمة. لذلك نُبقي المرجع في الـ JSON ونحذفه من العرض فقط —
 * فلا نفقد ارتباط المحتوى بالكتاب ولا نُثقل الشاشة.
 */

/** يحذف مراجع الأقسام (§N · §N.N) وما يتبقّى من فواصل معلّقة */
export function cleanLabel(text: string | null | undefined): string {
  if (!text) return '';

  return (
    text
      // §2 · §8.2 · § 10 — مع أو بلا مسافة
      .replace(/§\s*\d+(\.\d+)*/g, '')
      // فواصل صارت معلّقة بعد الحذف: «+ العائلة» أو «النطق —»
      .replace(/\s*[–—-]\s*$/g, '')
      .replace(/^\s*[+–—-]\s*/g, '')
      .replace(/\s*\+\s*$/g, '')
      // مسافات مكرّرة، ومسافة قبل نقطتين أو فاصلة
      .replace(/\s{2,}/g, ' ')
      .replace(/\s+([:،,.])/g, '$1')
      .trim()
  );
}
